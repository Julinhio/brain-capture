// Rebuilds src/server/nutrition/ciqual-data.ts from the Ciqual table published by Anses
// (French food composition table, Licence Ouverte / CC-BY 4.0).
//
//   node scripts/build-ciqual.mjs <folder with alim_*.xml and compo_*.xml>
//
// The XML files come from https://ciqual.anses.fr (or its Zenodo record,
// doi:10.5281/zenodo.17550133 for the 2025 table). They are not kept in the repository: the
// composition file alone weighs 69 MB. Only what the app uses is kept, per 100 g of food:
// energy (kcal, EU regulation 1169/2011), protein, carbohydrate and fat.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const KCAL = '328';
const PROTEIN = '25000';
const CARBS = '31000';
const FAT = '40000';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/build-ciqual.mjs <folder with alim_*.xml and compo_*.xml>');
  process.exit(1);
}
const find = (prefix) => {
  const name = readdirSync(dir).find((f) => f.startsWith(prefix) && !f.startsWith('alim_grp') && f.endsWith('.xml'));
  if (!name) throw new Error(`No ${prefix}*.xml in ${dir}`);
  return path.join(dir, name);
};
const alimFile = find('alim_');
const compoFile = find('compo_');

const unescape = (s) =>
  s.replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const field = (block, tag) => {
  const m = block.match(new RegExp(`<${tag}>([^<]*)</${tag}>`));
  return m ? unescape(m[1]).trim() : null;
};

/** "12,5" → 12.5; "< 0,5" → half the bound; "traces" → 0; "-" or missing → null. */
function amount(raw) {
  if (raw === null || raw === '' || raw === '-') return null;
  if (/^traces?$/i.test(raw)) return 0;
  const below = raw.startsWith('<');
  const n = Number(raw.replace('<', '').trim().replace(',', '.'));
  if (!Number.isFinite(n)) return null;
  return below ? n / 2 : n;
}

const foods = new Map();
for (const block of readFileSync(alimFile, 'utf8').split('<ALIM>').slice(1)) {
  const code = field(block, 'alim_code');
  const name = field(block, 'alim_nom_fr');
  if (code && name) foods.set(code, { code: Number(code), name: name.replace(/\s+/g, ' ') });
}

const wanted = new Map([
  [KCAL, 'kcal'],
  [PROTEIN, 'protein'],
  [CARBS, 'carbs'],
  [FAT, 'fat'],
]);
for (const block of readFileSync(compoFile, 'utf8').split('<COMPO>').slice(1)) {
  const key = wanted.get(field(block, 'const_code') ?? '');
  if (!key) continue;
  const food = foods.get(field(block, 'alim_code') ?? '');
  if (food) food[key] = amount(field(block, 'teneur'));
}

const round = (n) => Math.round(n * 10) / 10;
const rows = [...foods.values()]
  // Without energy an entry cannot give calories; the three macros default to 0 when the
  // table has no value (mostly waters, salts and spices).
  .filter((f) => typeof f.kcal === 'number')
  .sort((a, b) => a.code - b.code)
  .map((f) => [f.code, f.name, Math.round(f.kcal), round(f.protein ?? 0), round(f.carbs ?? 0), round(f.fat ?? 0)]);

const version = path.basename(alimFile).match(/alim_(\d{4})/)?.[1] ?? 'unknown';
const out = [
  '// Generated by scripts/build-ciqual.mjs. Do not edit by hand.',
  `// Source: Anses, Ciqual French food composition table ${version} (Licence Ouverte / CC-BY 4.0), https://ciqual.anses.fr`,
  '// Each row: [Ciqual code, French name, kcal, protein g, carbohydrate g, fat g], per 100 g.',
  `export const CIQUAL_VERSION = '${version}';`,
  'export type CiqualRow = readonly [code: number, name: string, kcal: number, protein: number, carbs: number, fat: number];',
  'export const CIQUAL: readonly CiqualRow[] = [',
  ...rows.map((r) => `  ${JSON.stringify(r)},`),
  '];',
  '',
].join('\n');
const target = path.resolve('src/server/nutrition/ciqual-data.ts');
writeFileSync(target, out);
console.log(`${rows.length} foods written to ${target} (${foods.size - rows.length} without energy skipped)`);
